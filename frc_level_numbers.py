"""
frc_level_numbers.py -- regenerates every number in HANDOVER's entry on WHERE
THE ANAESTHETISED FRC LEVEL COMES FROM, and fails if one has drifted.

Same contract as handover_numbers.py, buccal_numbers.py and aa_numbers.py:
NOT in the pre-commit hook, because these are claims about the world rather
than invariants of the code, and they are EXPECTED to move when the model is
corrected. The point is that they must not move SILENTLY.

Fast -- a few seconds. Every number here is a lung volume, so nothing is
simulated. The benchmark COST of the switch is a different question and is
regenerated by `python3 variant_cost.py frc_abs`, which is a full suite run.

    python3 frc_level_numbers.py

Published sources only: Pelosi 1998 and Damia 1988 for the anaesthetised FRC
curve, Watson & Pride for the awake re-solve that 48ffe03 performed, and the
Toner / Heard / Berthoud cohorts as already recorded in test_validation.py.
"""
import dataclasses

import numpy as np

import apnoea_core as A
from apnoea_core import Patient

print(A.provenance())
print()

# Pelosi 1998's own cohort geometry, as handover_numbers.py already uses it.
PELOSI_GEO = dict(height=1.64, age=52.0, hb=14.0, tilt_deg=0.0)
# The three benchmarked cohorts, copied from test_validation.py.
TONER = dict(weight=70, height=1.75, age=45, hb=15, tilt_deg=0)
BERTHOUD = dict(weight=70, height=1.745, age=40, hb=14, tilt_deg=0)
HEARD = dict(weight=105, height=1.74, age=42, hb=14, tilt_deg=30)

MEAN_C = 0.6882      # the ruled offset: mean of Pelosi 0.4600 and Damia 0.9163
FAILED = []


def check(name, got, want, tol, unit=""):
    ok = abs(got - want) <= tol
    if not ok:
        FAILED.append(name)
    print(f"  {'ok  ' if ok else 'FAIL'} {name:<52}{got:>9.2f}{unit}"
          f"   recorded {want}{unit}")


def absolute(offset=MEAN_C):
    """Patient subclass with the de-coupled level, optionally at another offset.

    The switch is a plain CLASS ATTRIBUTE so ordinary subclassing works. See
    variant_cost.py's _variant_class for the dataclass-field trap this avoids.
    """
    @dataclasses.dataclass
    class V(Patient):
        frc_anaes_absolute = True
        pelosi_offset_l = offset
    return V


print("1. THE SHIPPED LEVEL IS AWAKE-DERIVED, AND THE ERROR IT CARRIES IS A")
print("   CONSTANT. frc_anaes() -- lung volume at the start of apnoea -- sets")
print("   its level at frc_ref * height_factor * tilt_factor minus an")
print("   induction drop. frc_ref is commented in apnoea_core.py as 'mL")
print("   supine AWAKE at BMI 22'; frc_drop is a CHANGE from awake. Pelosi")
print("   and Damia both measured the ANAESTHETISED volume directly, so the")
print("   level has a source and the model is not using it.")
print()
print("   Scored at Pelosi's geometry against the Pelosi/Damia mean the model")
print("   has targeted since bffbbf4 (2026-09-26):")
curve = lambda b: 11.97 * np.exp(-0.096 * b) * 1000.0 + MEAN_C * 1000.0
for _b in (22, 26, 30, 40, 50, 66):
    _p = Patient(weight=_b * 1.64 ** 2, **PELOSI_GEO)
    check(f"BMI {_b}: shipped level error vs its own target",
          100.0 * (_p.frc_anaes() - curve(_b)) / curve(_b), 3.67, 0.02, " %")
print()
print("   THE SAME NUMBER AT EVERY BMI. The shape is carried as a ratio and is")
print("   exact by construction, so the only thing this comparison can see is")
print("   the LEVEL. The 3.67 % recorded on 2026-10-12 was read then as being")
print("   'very nearly right' and as showing 'no awake/anaesthetised coupling")
print("   to fix'. It is not scatter about a curve. It is a pure systematic")
print("   bias and its whole size is the awake anchor.")
print()
_p20 = Patient(weight=20 * 1.64 ** 2, **PELOSI_GEO)
check("BMI 20: error (the awake bound binds here)",
      100.0 * (_p20.frc_anaes() - curve(20)) / curve(20), -7.01, 0.02, " %")
print("   Below about BMI 22 the curve extrapolates the anaesthetised lung")
print("   ABOVE the awake one, which is impossible, so `awake - drop` caps it.")
print()

print("2. THE CASCADE, DECOMPOSED AT TONER'S GEOMETRY. 48ffe03 (2026-09-26)")
print("   re-solved frc_awake on Watson & Pride's two SUPINE AWAKE cohorts,")
print("   moving frc_ref 2500 -> 2860 mL and k_frc_bmi 0.0012 -> 0.01074. It")
print("   added 71 s to a desaturation benchmark. Which parameter did it:")
check("frc_ref 2860 (shipped), anaes volume",
      Patient(**TONER).frc_anaes(), 2328.3, 0.1, " mL")
check("frc_ref 2500 only, anaes volume",
      Patient(frc_ref=2500.0, **TONER).frc_anaes(), 1987.6, 0.1, " mL")
check("k_frc_bmi 0.0012 only, anaes volume",
      Patient(k_frc_bmi=0.0012, **TONER).frc_anaes(), 2328.3, 0.1, " mL")
print("   frc_ref accounts for ALL 340.7 mL. k_frc_bmi moves it by EXACTLY")
print("   ZERO, because Pelosi's shape now carries the BMI dependence and the")
print("   awake exponential no longer reaches this quantity. So a ruling made")
print("   correctly, on awake data, re-aimed the anaesthetised benchmarks")
print("   through one parameter, and nothing in the repository flagged it.")
print()

print("3. WHAT DE-COUPLING WOULD HAVE DONE TO THAT SAME COMMIT, and why it is")
print("   NOT independence:")
check("de-coupled, frc_ref 2500, anaes volume",
      absolute()(frc_ref=2500.0, **TONER).frc_anaes(), 2077.1, 0.1, " mL")
check("de-coupled, frc_ref 2860, anaes volume",
      absolute()(**TONER).frc_anaes(), 2211.5, 0.1, " mL")
print("   +134 mL instead of +341. NOT ZERO: Toner's patient is LEAN, so the")
print("   curve's own level sits ABOVE `awake - drop` and the bound binds at")
print("   the lower frc_ref. The surviving coupling runs only through the")
print("   PHYSICAL BOUND and only in lean patients. That is far smaller and")
print("   far more defensible than inheriting the level, but it is not")
print("   independence and must not be recorded as independence.")
print()

print("4. DE-COUPLING MAKES THE UNRULED OFFSET QUESTION LOAD-BEARING, AND THIS")
print("   IS THE REASON NOT TO ADOPT IT YET. Shipped, the offset is very")
print("   nearly divided out by the ratio form. De-coupled, it SETS the level:")
print()
print(f"   {'cohort':<22}{'shipped':>10}{'C=0.460':>10}{'C=0.688':>10}{'C=0.916':>10}")
print(f"   {'':22}{'':>10}{'Pelosi':>10}{'ruled':>10}{'Damia':>10}")
for _name, _geo, _rec in (("Berthoud lean BMI 23", BERTHOUD,
                           (2298.6, 1936.1, 2184.8, 2418.8)),
                          ("Toner lean BMI 22.9", TONER,
                           (2328.3, 1962.0, 2211.5, 2433.8)),
                          ("Heard obese BMI 34.7", HEARD,
                           (1713.2, 1249.7, 1570.5, 1891.3))):
    _got = [Patient(**_geo).frc_anaes()] + [
        absolute(_c)(**_geo).frc_anaes() for _c in (0.4600, MEAN_C, 0.9163)]
    print(f"   {_name:<22}" + "".join(f"{v:>10.1f}" for v in _got))
    for _lbl, _g, _w in zip(("shipped", "C=0.460", "C=0.688", "C=0.916"),
                            _got, _rec):
        if abs(_g - _w) > 0.2:
            FAILED.append(f"{_name} {_lbl}")
print()
_sp_lean = 100.0 * (2418.8 - 1936.1) / 1936.1
_sp_ob = 100.0 * (1891.3 - 1249.7) / 1249.7
check("spread across the two offsets, LEAN", _sp_lean, 24.93, 0.05, " %")
check("spread across the two offsets, OBESE", _sp_ob, 51.34, 0.05, " %")
print("   The offset IS the asymptote, so it bites hardest where the")
print("   exponential has decayed -- in the obese. Choosing between Pelosi's")
print("   0.46, Damia's 0.92 and the ruled mean currently changes a lean")
print("   anaesthetised FRC by a quarter and an obese one by a half. That")
print("   choice has been unruled since 2026-09-26, when it mattered much")
print("   less than it would matter after de-coupling.")
print()

print("5. THE BENCHMARK COST, measured 2026-10-13 over two full suite runs.")
print("   Regenerate with `python3 variant_cost.py shipped` and")
print("   `python3 variant_cost.py frc_abs`, then `variant_cost.py --diff`.")
print("   NOT recomputed here -- each run is ~34 min, and a number that takes")
print("   half an hour does not belong behind a script that claims to be fast.")
print()
print("     row                              shipped    de-coupled   band")
print("     Heard control, SpO2<95%          318.5 FAIL  294.5 pass  244-314 s")
print("     Berthoud control BMI 23          548.6 pass  530.3 FAIL  537-653 s")
print("     Toner sham, SpO2<95%             509.1 pass  485.6 pass  380-525 s")
print("     Berthoud obese BMI 49            201.7 pass  197.3 pass  163-229 s")
print("     Stock obstructed, PaO2 at 5 min  275.5 pass  232.7 pass  140-488 mmHg")
print()
print("   45 pass / 2 fail BOTH WAYS, and the two failures are DIFFERENT rows.")
print("   De-coupling FIXES the obese benchmark and BREAKS a lean one. That is")
print("   a trade, not an improvement, and it is what the mechanism predicts:")
print("   removing the awake anchor lowers FRC everywhere above BMI 22, which")
print("   helps a row that ran too long and hurts one with no headroom.")
print()
print("   AND THE WINDOW BETWEEN THEM IS NOT A LICENCE. Heard needs about")
print("   1.4 % off and Berthoud tolerates about 2.1 %, so SOME level cut")
print("   between them would pass both. Choosing a cut because it passes two")
print("   benchmarks is a fit, and this project has refused that four times.")
print("   The de-coupled level is not free: it is fixed by the two papers, and")
print("   it overshoots. The honest routes are to accept the trade or to rule")
print("   on the offset -- not to pick a number in the gap.")
print()

if FAILED:
    print(f"{len(FAILED)} value(s) have drifted:")
    for f in FAILED:
        print(f"  - {f}")
    raise SystemExit(1)
print("Every FRC-level number still reproduces from this commit.")
