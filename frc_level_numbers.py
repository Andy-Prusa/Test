"""
frc_level_numbers.py -- regenerates every number in HANDOVER's entry on WHERE
THE ANAESTHETISED FRC LEVEL COMES FROM, and fails if one has drifted.

Same contract as handover_numbers.py, buccal_numbers.py and aa_numbers.py:
NOT in the pre-commit hook, because these are claims about the world rather
than invariants of the code, and they are EXPECTED to move when the model is
corrected. The point is that they must not move SILENTLY.

Fast -- a few seconds. Every number here is a lung volume, so nothing is
simulated. The benchmark COST of the switch is a different question and is
regenerated by `python3 variant_cost.py frc_abs`, which is a full suite run.

    python3 frc_level_numbers.py

Published sources only: Pelosi 1998 and Damia 1988 for the anaesthetised FRC
curve, Watson & Pride for the awake re-solve that 48ffe03 performed, and the
Toner / Heard / Berthoud cohorts as already recorded in test_validation.py.
"""
